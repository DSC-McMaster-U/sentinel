from typing import Literal

from pydantic import BaseModel, Field, model_validator

from .finding import SecurityFinding
from .pull_request import ChangedFile


class AgentInput(BaseModel):
    """PR context selected by the workflow for this agent."""

    pr_number: int = Field(ge=1)
    commit_sha: str = Field(min_length=1)
    repo_url: str = Field(
        min_length=1, description="The URL of the repository containing the pull request."
    )
    changed_files: list[ChangedFile] = Field(
        min_length=1, description="Relevant files and patches selected for this agent."
    )


class AgentOutput(BaseModel):
    """Output data from an agent after processing a security finding."""

    agent_name: str = Field(
        min_length=1, description="The name of the agent that generated the finding."
    )
    findings: list[SecurityFinding] = Field(
        description="The security findings generated by the agent."
    )
    status: Literal["success", "failure", "partial"] = Field(
        description="The status of the agent's processing."
    )
    error_message: str | None = Field(
        default=None, description="An error message if processing failed or was partial."
    )

    @model_validator(mode="after")
    def validate_consistency(self) -> "AgentOutput":
        if self.status == "success":
            if self.error_message is not None:
                raise ValueError("Successful output must not include an error_message")
        elif self.error_message is None or not self.error_message.strip():
            raise ValueError("Failure or partial output requires a nonblank error_message")

        for finding in self.findings:
            if finding.agent != self.agent_name:
                raise ValueError("Each finding's agent must match agent_name")

        return self
