from typing import Literal

from pydantic import BaseModel, Field

from .finding import SecurityFinding


class ChangedFile(BaseModel):
    file_path: str
    patch: str


class AgentInput(BaseModel):
    """PR context selected by the workflow for this agent."""

    pr_number: int = Field(ge=1)
    commit_sha: str
    repo_url: str = Field(min_length=1, description="The URL of the repository containing the pull request.")
    changed_files: list[ChangedFile] = Field(
        min_length=1, description="Relevant files and patches selected for this agent."
    )


class AgentOutput(BaseModel):
    """Output data from an agent after processing a security finding."""
    agent_name: str = Field(min_length=1, description="The name of the agent that generated the finding.")
    findings: list[SecurityFinding] = Field(description="The security findings generated by the agent.")
    status: Literal["success", "failure", "partial"] = Field(description="The status of the agent's processing.")
    error_message: str | None = Field(default=None, description="An error message if the agent failed to process the input.")
